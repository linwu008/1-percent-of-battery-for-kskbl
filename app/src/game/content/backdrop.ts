/** 拼出这一局的处境说明。返回若干段落，界面逐段显示。 */
export function backdrop(seed: string, env: Env): string[] {
  const d = pick(seed, "bd:disaster", DISASTER[env.disaster] ?? DISASTER.earthquake);
  const l = pick(seed, "bd:daylight", DAYLIGHT[env.daylight] ?? DAYLIGHT.night);
  const t = pick(seed, "bd:temp", TEMP[env.temp] ?? TEMP.cool);
  const i = pick(seed, "bd:injury", INJURY[env.injury] ?? INJURY.none);
  const c = pick(seed, "bd:carry", CARRY[env.carry] ?? CARRY.none);
  const n = pick(seed, "bd:network", NETWORK[env.network] ?? NETWORK.dead);

  return [
    `${d}${l}`,
    `${i}${c}${n}`,
    "你的手机还剩 1.000%。它不够打一通电话，也不够撑到有人找到你。" +
      "它能做的只有一件事：把这几样信息送出去——你在哪、有几个人、你们还撑得住多久。" +
      "每做一个动作电就少一点；就算你什么都不做，电池也在自己往下掉。" +
      "所以这不是「省着就能赢」的题，是「把这点电花在哪儿」的题。",
  ];
}
